const defaultLocale: MiniLocale = "vi-VN";

const isMiniLocale = (value: string | null | undefined): value is MiniLocale =>
  value === "vi-VN" || value === "en-US";

const readStoredLocale = (): MiniLocale => {
  try {
    const storedLocale = window.localStorage.getItem(MINI_LOCALE_STORAGE_KEY);
    return isMiniLocale(storedLocale) ? storedLocale : defaultLocale;
  } catch {
    return defaultLocale;
  }
};

