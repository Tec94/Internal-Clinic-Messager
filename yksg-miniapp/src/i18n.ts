export const getActiveMiniLocale = (): MiniLocale =>
  isMiniLocale(i18n.resolvedLanguage) ? i18n.resolvedLanguage : defaultLocale;

export const setMiniLocale = async (locale: MiniLocale): Promise<void> => {
  try {
    window.localStorage.setItem(MINI_LOCALE_STORAGE_KEY, locale);
  } catch {
    // The selector still works for this session when storage is unavailable.
  }
  document.documentElement.lang = locale;
  await i18n.changeLanguage(locale);
};

